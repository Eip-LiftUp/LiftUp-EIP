-- Migration 0008: Create cached_programs table
--
-- Stores the last training program generated for each user, so that
-- GET /workouts/program can still answer when the AI service is down.
-- A dedicated table (instead of a JSONB column on users) keeps the large
-- program out of every `SELECT * FROM users`, and ON DELETE CASCADE removes
-- the cached data with the user (GDPR erasure).

CREATE TABLE IF NOT EXISTS cached_programs (
    user_id UUID PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    program JSONB NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Reuse the function created in migration 0001
CREATE TRIGGER set_cached_programs_updated_at
    BEFORE UPDATE ON cached_programs
    FOR EACH ROW
    EXECUTE FUNCTION trigger_set_updated_at();

COMMENT ON TABLE cached_programs IS 'Last known training program of each user (one row per user), served as a fallback when the AI service is unavailable';
COMMENT ON COLUMN cached_programs.user_id IS 'Owner of the cached program; primary key, so a user has at most one cached program. Row deleted with the user (CASCADE)';
COMMENT ON COLUMN cached_programs.program IS 'Serialized ProgramResponse (camelCase JSON): {"generatedAt": ..., "source": ..., "workouts": [...]}';
COMMENT ON COLUMN cached_programs.generated_at IS 'When the program was last generated by the AI service; reset on every upsert';
COMMENT ON COLUMN cached_programs.created_at IS 'When the row was first inserted';
COMMENT ON COLUMN cached_programs.updated_at IS 'Last modification time, maintained by the set_cached_programs_updated_at trigger';
