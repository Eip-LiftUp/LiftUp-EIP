//! Response models of `GET /workouts/program`.
//!
//! They must stay in sync with the `ProgramResponse` schema of `openapi.yaml`.
//! The schema is provisional: the ML engine contract is not frozen yet.

use chrono::{DateTime, Utc};
use serde::Serialize;
use sqlx::FromRow;
use uuid::Uuid;

use super::workout::WeightUnit;

/// A training program, as returned by `GET /workouts/program`.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ProgramResponse {
    /// When the program was produced by the ML engine.
    pub generated_at: DateTime<Utc>,
    /// Whether the program was just generated or served from cache.
    pub source: ProgramSource,
    /// The workouts that make up the program.
    pub workouts: Vec<ProgramWorkout>,
}

/// Origin of a [`ProgramResponse`].
#[derive(Debug, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum ProgramSource {
    /// Freshly produced by the ML engine.
    Generated,
    /// Last known program, used when the engine is unavailable.
    Cache,
}

/// One workout of a program.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ProgramWorkout {
    /// Display name of the workout.
    pub name: String,
    /// Exercises to perform, in order.
    pub exercises: Vec<ProgramExercise>,
}

/// One exercise of a program workout.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ProgramExercise {
    /// Name of the exercise.
    pub exercise_name: String,
    /// Number of sets.
    pub sets: i32,
    /// Number of repetitions per set.
    pub reps: i32,
    /// Load; `None` (serialized as `null`) for bodyweight exercises.
    pub weight: Option<f64>,
    /// Unit of `weight` (`kg` or `lbs`).
    pub weight_unit: WeightUnit,
}

/// A cached program, mapped 1-to-1 with the `cached_programs` table.
///
/// One row per user: the last program known, used as a fallback when the AI
/// service is unavailable.
#[derive(Debug, Clone, FromRow)]
pub struct CachedProgram {
    /// Owner of the program.
    pub user_id: Uuid,
    /// Serialized [`ProgramResponse`]; kept as raw JSON so the (provisional)
    /// schema can change without a database migration.
    pub program: serde_json::Value,
    /// When the program was last generated by the AI service.
    pub generated_at: DateTime<Utc>,
    /// When the row was first inserted.
    pub created_at: DateTime<Utc>,
    /// Last modification time (maintained by a database trigger).
    pub updated_at: DateTime<Utc>,
}
